class NaturalError(Exception):
    """Исключение для ошибок, связанных с натуральными числами"""
    pass


class IntegerError(Exception):
    """Исключение для ошибок, связанных с целыми числами"""
    pass


class RationalError(Exception):
    """Исключение для ошибок, связанных с рациональными числами"""
    pass


class PolynomialError(Exception):
    """Исключение для ошибок, связанных с многочленами"""
    pass